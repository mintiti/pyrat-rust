fn typescript_bindings() -> Typescript {
    Typescript::default()
        .bigint(BigIntExportBehavior::Number)
        .header("// This file is auto-generated by specta. Do not edit.")
}

fn rendered_typescript_bindings() -> Result<String, specta_typescript::ExportError> {
    let rendered = bindings_builder().export_str(typescript_bindings())?;
    let had_trailing_newline = rendered.ends_with('\n');
    let mut normalized = rendered
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");
    if had_trailing_newline {
        normalized.push('\n');
    }
    Ok(normalized)
}

fn main() {
    tracing_subscriber::fmt()
        .with_env_filter(
            // Default to a calm terminal: host runs at `info`, so per-turn
            // recovery (`move timeout`, stale-action — all `debug!`) stays
            // quiet during a tournament. Bot subprocess stderr is forwarded
            // under the `bot_stderr` target (see `forward_bot_stderr`), which
            // the bare `warn` default suppresses. Opt back in per source:
            // `RUST_LOG=pyrat_host=debug` for host internals,
            // `RUST_LOG=bot_stderr=debug` for raw bot output.
            tracing_subscriber::EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| "pyrat_gui=debug,pyrat_host=info,warn".parse().unwrap()),
        )
        .init();

    let builder = bindings_builder();

    #[cfg(debug_assertions)]
    std::fs::write(
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/bindings/generated.ts"),
        rendered_typescript_bindings().expect("failed to render typescript bindings"),
    )
    .expect("failed to export typescript bindings");

    let app = tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .manage(state::AppState::default())
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            Ok(())
        })
        .build(tauri::generate_context!())
        .expect("error while building tauri application");

    // 0 = normal, 1 = draining an owned tournament, 2 = programmatic exit
    // after the bounded drain. Repeated native exit requests during state 1
    // must remain prevented; state 2 lets `AppHandle::exit` pass through.
    let exit_phase = Arc::new(AtomicU8::new(0));
    app.run(move |app_handle, event| {
        let tauri::RunEvent::ExitRequested { api, .. } = event else {
            return;
        };
        match exit_phase.load(Ordering::Acquire) {
            2 => return,
            1 => {
                api.prevent_exit();
                return;
            },
            _ => {},
        }
        let state = app_handle.state::<state::AppState>();
        let has_owned_tournament = state
            .tournament_phase
            .try_lock()
            .map(|phase| !matches!(*phase, state::TournamentPhase::Idle))
            .unwrap_or(true);
        if !has_owned_tournament {
            return;
        }

        api.prevent_exit();
        if exit_phase.swap(1, Ordering::AcqRel) != 0 {
            return;
        }
        let app_handle = app_handle.clone();
        let exit_phase = exit_phase.clone();
        tauri::async_runtime::spawn(async move {
            let state = app_handle.state::<state::AppState>();
            if let Err(error) = shutdown_tournament_for_app(&app_handle, &state).await {
                tracing::error!(error = %error, "could not finalize tournament before exit");
            }
            exit_phase.store(2, Ordering::Release);
            app_handle.exit(0);
        });
    });
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn committed_typescript_bindings_are_current() {
        assert_eq!(
            rendered_typescript_bindings().expect("render TypeScript bindings"),
            include_str!("../../src/bindings/generated.ts"),
            "run `cargo test -p pyrat-gui regenerate_typescript_bindings -- --ignored`",
        );
    }

    #[test]
    #[ignore = "rewrites gui/src/bindings/generated.ts"]
    fn regenerate_typescript_bindings() {
        let path =
            std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/bindings/generated.ts");
        std::fs::write(
            path,
            rendered_typescript_bindings().expect("render TypeScript bindings"),
        )
        .expect("write TypeScript bindings");
    }
}
